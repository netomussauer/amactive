// Monta a query string de um GET a partir de um objeto de filtros, ignorando
// valores undefined/null/'' — usado pelos services das features.
export function buildQueryString(params: Record<string, unknown> | undefined): string {
  if (!params) return ''
  const search = new URLSearchParams()
  for (const [key, value] of Object.entries(params)) {
    if (value === undefined || value === null || value === '') continue
    search.set(key, String(value))
  }
  const qs = search.toString()
  return qs ? `?${qs}` : ''
}
